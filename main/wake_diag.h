/*
 * wake_diag.h — 깨어남 출처 계측 (2026-08-20)
 * ────────────────────────────────────────────────────────────────────────
 * 왜 필요한가: 배터리 실측에서 **90회/초** 깨어나는데, 태스크 주기를 전수
 * 조사해 더하면 54회/초뿐이다(btn 25ms=40 + 메인 100ms=10 + oled 500ms=2 +
 * hold 500ms=2). 겹침(coalescing)은 줄이기만 하므로 초과분을 설명 못 한다.
 *
 * 이미 소거된 후보:
 *   · 배터리 구간 LP 정지    → [PWR] 이 `LP=ON 폴25ms` 로 정상 확인
 *   · LP 가 PCF 지터로 깨움  → [LPWAKE] `HP 깨우기 0.00회/초` (2분 연속 0)
 *
 * 남은 결정적 사실: 수면 길이 85,227표본 중 **20ms 를 넘은 것이 한 번도 없다**.
 * 버튼 폴이 25ms 인데 그 간격이 안 나온다 = 그 전에 항상 다른 것이 깨운다.
 *
 * 그래서 두 가지를 동시에 센다:
 *   ① `esp_sleep_get_wakeup_cause()` 분포 — 타이머인가, GPIO/ULP/무선인가
 *   ② 우리 태스크의 **실제 반복 횟수** — 추정한 주기가 맞는지 검증하고,
 *      "깨어남 − 우리 반복" 이 곧 남의 몫(CHIP/OpenThread 등)이 된다.
 * 둘 다 NVS 로 남겨 배터리 구간에서도 읽는다(USB 콘솔은 절전 중 죽는다).
 */
#include <stdint.h>

