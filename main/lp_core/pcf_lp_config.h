/*
 * pcf_lp_config.h — LP 코어 프로그램과 HP 가 **함께 보는** 최소 설정
 * ═══════════════════════════════════════════════════════════════════
 * LP 코어 툴체인은 HP 쪽 헤더 체인(button_handler.h → FreeRTOS/esp_log …)을
 * 따라갈 수 없다. 그렇다고 값을 양쪽에 따로 적으면 **조용히 어긋난다** —
 * 실제로 LP 가 1바이트만 읽어 좌/우 버튼(PCF8575 P10/P11 = bit8/9)이 통째로
 * 사라졌다(2026-08-13 실사용 신고).
 *
 * ★그래서 이 파일 하나만 **양쪽이 같이 include** 하고, HP 쪽에서
 *   `_Static_assert(LP_PCF_NBYTES == PCF_NBYTES, ...)` 로 어긋남을 **빌드에서**
 *   잡는다. 런타임에 조용히 틀리는 것보다 컴파일이 깨지는 게 낫다.
 *
 * ※빌드 정의(-D)로 넘기는 방법은 못 쓴다: ulp_embed_binary 가 만드는 타깃은
 *   ExternalProject 라 target_compile_options 가 통하지 않는다
 *   ("target_compile_options called with non-compilable target type").
 */
#pragma once

/* PCF 확장기 read 폭(바이트).
 *   2 = PCF8575(16비트, 좌/우 버튼 있음) ← xiao-c6 기본
 *   1 = PCF8574(8비트)
 * button_handler.h 의 PCF_NBYTES 와 반드시 같아야 한다(위 static assert 가 검증). */
#define LP_PCF_NBYTES 2

/* 로터리 A/B 비트 위치 — **물리 배치 고정**(P0=A, P1=B).
 * ★2026-08-31 배선이 뒤바뀐 개체(BOARD_ROT_AB_SWAP=1, 예 COM8)라도 **여기는
 *   바꾸지 않는다.** LP 코어는 빌드 -D 를 받을 수 없어(위 머리말 참조) 이 값이
 *   전 보드 공통이기 때문이다. 스왑 보정은 HP 쪽에서 방향을 뒤집어 처리한다
 *   (button_handler.c 의 `#if BOARD_ROT_AB_SWAP  cw = !cw;`).
 *   A/B 교환 == 쿼드러처 delta 부호 반전이므로 결과는 동일하다. */
#define LP_BIT_ROT_A  0
#define LP_BIT_ROT_B  1

/* ★★2026-09-01 LP 폴 주기(us) — **LP·HP 가 함께 쓴다.**
 *  HP 는 이 값을 `ulp_lp_core_cfg_t.lp_timer_sleep_duration_us` 에 넣어
 *  LP 코어를 이 주기로 깨운다(1회 실행 후 halt). LP 는 같은 값으로 동작한다.
 *  두 곳에 따로 적으면 조용히 어긋나므로 — 이 헤더의 존재 이유대로 — 여기 하나만 둔다.
 *
 *  값 근거(2026-08-27 시뮬 sim/tools/power_lever_sim.py): 로터리 20디텐트 CW 를
 *  폴 주기별로 디코딩하면 5000us 까지는 전부 +20, 8000us 부터 빠른 회전에서
 *  손실이 난다. **버튼은 press_latch 가 모아주지만 로터리는 래치가 없어**
 *  로터리가 진짜 제약이다. 늘리지 말 것. */
#define LP_POLL_US  5000

/* ★★2026-10-31 로터리 핀 **주차** — LP 가 쉬는 로터리의 닫힌 접점 핀을 PCF 출력 LOW 로 몰아 둔다.
 *  하프스텝 로터리는 디텐트가 11 과 00 을 번갈아 쓴다. 00(두 접점 닫힘)에 멈추면 PCF8575 의 '1 쓰기 = 약한 전류원'
 *  (핀당 30~300µA)이 접점으로 **계속** 흐른다(10/30 lsfloor rot: 0.13±0.36mA, 접점당 66µA — 범위 넓음).
 *  '0 쓰기 = 강한 LOW' 면 접점과 같은 GND 라 전류 0. 그 대신 다음 폴은 **놓고 읽는다**(0xFFFF 쓰기 → 반복 START → 읽기,
 *  한 트랜잭션) — 몰아 둔 LOW 를 접점으로 오독하지 않는다(sim/tools/rot_park_sim.py ②~⑤).
 *  · 폴 주기는 **그대로**다. 주차 중 폴 1회가 ~0.17ms 길어질 뿐(LP 타이머는 halt 뒤부터 센다).
 *  · 그래서 **돌리는 동안엔 주차하지 않는다** — 로터리 비트가 LP_ROT_PARK_IDLE_POLLS 폴(200ms) 동안 그대로일 때만.
 *    처음엔 늘 주차했더니 실효 주기가 3% 늘어 한계 밖 속도(12ms/디텐트)에서 놓침이 57→68 로 늘었다. 지금은 57→59(같은 수준),
 *    20ms/디텐트 이하 속도는 옛·새 둘 다 0.
 *  · 11(열림) 정지는 몰 핀이 없어 **옛 동작과 완전히 같다**(추가 I2C 0).
 *  · 00 정지: 전류원 흐름 시간 100% → ~2.5%, I2C 버스 활성 +2.6%(초당 +26ms, 400kHz).
 *  0 = 끔(옛 동작). HP 가 공유 RAM park_en 으로 끄고 켤 수 있다(lsfloor park 측정). */
#define LP_ROT_PARK             1
#define LP_ROT_PARK_IDLE_POLLS  40

/* ★★2026-09-02 LP 구동 방식 스위치 — **회귀 원인 격리용**.
 *   1 = 폴 1회 후 halt + LP 타이머 기상 (2026-09-01 도입, 현재 기본)
 *   0 = while(1) + busy-wait delay + HP_CPU 1회 기상 (그 이전 방식)
 *  왜: halt 전환 뒤 실측에서 **깨어남 32.6 → 339회/초, sleep 96 → 81%** 로
 *  나빠졌다(COM7·COM8 각 7.1시간 배터리 세션). LP 코어 전력은 아꼈는데 HP 를
 *  훨씬 더 깨우는 맞바꿈이 된 것으로 의심된다 — LP 타이머 기상이
 *  esp_sleep_enable_ulp_wakeup() 을 통해 HP 까지 깨우는 구조일 수 있다.
 *  ※LP 코어는 빌드 -D 를 못 받으므로(머리말 참조) 이 헤더의 값을 직접 고쳐
 *    빌드해야 한다. 비교가 끝나면 결론을 주석으로 남기고 한쪽으로 고정할 것.
 *
 *  ★★2026-09-10 A/B 진행 중 — COM7=0 / COM8=1 로 같은 창을 잰다.
 *    가설은 위에 적은 "LP 타이머가 HP 를 깨운다"였으나 **IDF 소스로 반증됐다**:
 *    HP 기상은 LP_TIMER target[0], LP 코어는 target[1] 로 유닛도 인터럽트 경로도
 *    분리돼 있고(ulp_lp_core_lp_timer_shared.c: TIMER_ID 1 / sleep_modes.c:1861: 0),
 *    HP 는 `ulp_lp_core_wakeup_main_processor()` 의 명시적 PMU 소프트 인터럽트
 *    (PMU_LP_TRIGGER_HP)로만 깨어난다. 실측 기상원인도 ULP 가 아닌 TIMER 였다.
 *    → 기전은 아직 모른다. 그러니 **인과부터 재실측**한다(추정 금지).
 *
 *  기준선(2026-09-10, HALT=1 양쪽 11.7시간 배터리 세션, NVS pmdump):
 *      COM7 334.6회/초 · 평균 2.73ms · sleep 91.3%
 *      COM8 337.1회/초 · 평균 2.72ms · sleep 91.7%
 *    C6 는 절전 1회당 약 2.52ms 가 고정비용(REGDMA 382+480 · 발진기 재교정 194 ·
 *    LP/HP 기상대기 1796 · 도메인 동기 150 µs)이라, 평균 2.7ms 는 **자는 시간이
 *    자러 가는 비용과 거의 같다**는 뜻이다 — sleep 91% 중 진짜 절전은 7% 뿐이다.
 *    ★그래서 볼 지표는 sleep% 가 아니라 **초당 절전 횟수**다.
 *
 *  ★★★2026-09-11 A/B 종결 — **이 스위치는 무죄. 위 2026-09-02 귀속은 오진이다.**
 *    18.1시간 배터리, 나머지 펌웨어 완전 동일:
 *        COM7 HALT=0   32.4회/초 · 평균 30.37ms · sleep 98.3%
 *        COM8 HALT=1   31.7회/초 · 평균 31.00ms · sleep 98.4%
 *    차이 없음. 결정적으로, **같은 HALT=1 인 COM8 이 전날 337회/초 → 31.7회/초**가
 *    됐다. 스위치를 안 건드렸는데 10배 좋아졌으니 스위치가 원인일 수 없다.
 *
 *    진짜 원인은 **CHG_STAT 레벨 GPIO 웨이크**였다(somfy_app.c 의
 *    BOARD_CHG_STAT_ACTIVE_HIGH 블록 — 고임피던스 VBUS 분압 노드가 문턱 근처에서
 *    토글). 세션 차분으로 확정: 우리 태스크 29.7회/초는 그대로인데 "남의 몫"이
 *    309.3 → 8.4회/초로 사라졌고, GPIO 기상 누적은 8/29 50만 → 9/10 9,590만
 *    (12일간 +9,539만)에서 이번 18시간 +784회(COM8)로 멎었다.
 *    ★그 수정은 2026-09-02 작업본에 있었으나 **9/10 까지 플래시된 적이 없다.**
 *      그 사이 모든 배터리 세션이 고장난 펌웨어였고, 나는 그 오염된 숫자를
 *      이 스위치 탓으로 읽었다. "고쳤다"와 "실기에 올라갔다"는 다른 말이다 —
 *      회귀를 커밋에 귀속하기 전에 **그 커밋이 그 세션에서 실제로 돌았는지** 볼 것.
 *
 *    1 로 고정한다(HP 기상은 동률이라 나머지로 결정):
 *      · LP CPU 활성 듀티 100% → 약 3% (d1eaeb7)
 *      · light sleep 거부 35,838회(HALT=0) vs 1,135회(HALT=1) — 31배 차이 */
#define SOMFY_LP_HALT  1
