# -*- coding: utf-8 -*-
"""표시 % **변화율 제한** 검증.

신고(2026-08-27): C6 기기 화면에서 배터리 잔량이 **내려갔다가 다시 올라간다.**

원인 사슬:
  ① BAT_ADC 가 이따금 낮게 읽힌다(원인은 별도 건).
  ② 그 값이 표시 % 를 끌어내리고, 방전 중 하한(s_pct_floor)이 그 낮은 값에 잠긴다.
  ③ 정상값이 100mV 이상 5표본 연속 들어오면 **하한이 해제**되고 표시가 되올라간다.
     ③은 "0% 갇힘"을 풀려고 2026-08-23 에 넣은 장치다 — 의도대로 동작한 결과가
     사용자 눈에는 "잔량이 오락가락" 으로 보인다.

→ 근본 대응: **표시가 물리적으로 불가능한 속도로 내려가지 못하게** 한다.
   그러면 이상값이 애초에 화면에 안 나타나고, 하한도 잘못 잠기지 않으므로
   되올라가는 일도 사라진다(한 수정으로 양방향 해결).

물리적 상한: 실측 방전은 **9.94시간에 5%p**(C6) 수준이다 = 0.0014 %p/5초.
측정 주기 5초에 **1%p** 를 허용하면 실제보다 **700배 빠른** 셈이라 진짜 방전은
전혀 방해받지 않는다. 반대로 스파이크(한 번에 90%p 하락)는 100표본(8.3분)에
걸쳐 서서히만 반영되므로, 그 전에 값이 정상으로 돌아오면 화면에 티가 안 난다.

예외(즉시 반영해야 하는 경우):
  · 부팅 직후 첫 표본 — 제한하면 0% 에서 시작해 기어오른다.
  · USB 연결/해제 — 충전 천장(s_pct_ceil)이 따로 관리하므로 그쪽에 맡긴다.
"""

MEAS_S      = 5      # 측정 주기(초)
MAX_STEP_PCT = 1     # 1회 측정에서 허용하는 최대 하락 %p


def run(seq, limit=MAX_STEP_PCT):
    """seq: 전압환산 % 목록 → 화면에 나가는 % 목록"""
    disp = None
    out = []
    for p in seq:
        if disp is None:
            disp = p                      # 부팅 첫 표본은 그대로
        elif p < disp - limit:
            disp = disp - limit           # 하락은 제한
        else:
            disp = p                      # 상승·소폭 하락은 그대로
        out.append(disp)
    return out


def show(name, seq):
    out = run(seq)
    print('── %s ──' % name)
    print('   입력 %s' % ' '.join('%d' % x for x in seq))
    print('   화면 %s' % ' '.join('%d' % x for x in out))
    print('   최저 %d%% (입력 최저 %d%%)   흔들림 %s' % (
        min(out), min(seq),
        '없음' if all(b <= a for a, b in zip(out, out[1:])) else '★있음'))
    print()


if __name__ == '__main__':
    # ① 실측 8/23 형태: 한 표본만 급락 후 정상
    show('스파이크 1회 (92% → 0% → 정상)',
         [92, 92, 92, 0, 92, 92, 92, 92])

    # ② 스파이크가 3표본 이어짐(급락거부 한도를 넘김)
    show('스파이크 3표본 연속',
         [92, 92, 0, 0, 0, 92, 92, 92, 92, 92])

    # ③ 접촉 불량으로 오르내림 반복 — 사용자가 본 형태
    show('오르내림 반복 (하한 해제가 보이던 형태)',
         [40, 40, 12, 12, 40, 40, 12, 40, 40, 40])

    # ④ 진짜 방전 — 방해받지 않아야 한다
    show('정상 방전 (5초당 0.0014%p — 표에서는 계단 1회)',
         [40, 40, 40, 39, 39, 39, 39, 38])

    # ⑤ 진짜 급락(셀 수명 끝) — 제한되지만 결국 내려간다
    show('진짜 급락 (25% → 0%)',
         [25, 20, 15, 10, 5, 0, 0, 0, 0, 0, 0, 0])

    print('요약: 하락 제한 %d%%p/%d초 = 실측 방전의 약 700배 속도.'
          % (MAX_STEP_PCT, MEAS_S))
    print('      진짜 방전은 전혀 안 막히고, 스파이크는 화면에 안 나타난다.')
    print('      ★상승은 제한하지 않는다 — 충전 시 즉시 반영돼야 하고,')
    print('        방전 중 상승은 이미 하한(s_pct_floor)이 막는다.')
